// Generates src/i18n/cldr_intervals.zig, the patterns of ranges of dates
// and times of the locales src/i18n/date.zig lists, from the CLDR data of
// the JavaScript engine's Intl.DateTimeFormat (ICU's DateIntervalFormat,
// which formatRange follows), and src/i18n/testdata/intervals.json, the
// outputs the tests compare with.
//
//     bun scripts/i18n-intervals-cldr.mjs   (or node)
//
// A pattern is recovered from formatRangeToParts: each field part becomes
// its pattern letters, each literal quoted text, and the pattern splits
// where the parts of the range's end begin.
import { writeFileSync, mkdirSync } from "node:fs";

const locales = ["en", "en-GB", "de", "fr", "es", "it", "pt", "ru", "ja", "zh", "zh-Hant", "ko"];
const dateStyles = [null, "short", "medium", "long", "full"];
const timeStyles = [null, "short", "medium"];
// The fields two times first differ in, largest first.
const fields = ["y", "M", "d", "a", "h", "m", "s"];

const utc = (y, mo, d, h, mi, s) => new Date(Date.UTC(y, mo - 1, d, h, mi, s));
// January and February, whose abbreviated names are not their full ones.
const start = utc(2026, 1, 5, 9, 5, 7);
const ends = {
  y: utc(2027, 2, 6, 10, 6, 8),
  M: utc(2026, 2, 6, 10, 6, 8),
  d: utc(2026, 1, 6, 10, 6, 8),
  a: utc(2026, 1, 5, 15, 6, 8),
  h: utc(2026, 1, 5, 10, 6, 8),
  m: utc(2026, 1, 5, 9, 6, 8),
  s: utc(2026, 1, 5, 9, 5, 9),
};

const zig = (s) => '"' + Array.from(s).map((c) => {
  const p = c.codePointAt(0);
  if (c === '"' || c === "\\") return "\\" + c;
  if (p < 0x20 || p === 0x7f) return "\\x" + p.toString(16).padStart(2, "0");
  if (p >= 0x80 && (p < 0xa1 || (p >= 0x200b && p <= 0x200f) || (p >= 0x202a && p <= 0x202f) || p === 0x061c || p === 0x2066 || p === 0x2069)) return "\\u{" + p.toString(16) + "}";
  return c;
}).join("") + '"';

const quote = (text) => text.length === 0 ? "" : /^[^A-Za-z']*$/.test(text) ? text : "'" + text.replaceAll("'", "''") + "'";

const options = (date, time) => ({ timeZone: "UTC", numberingSystem: "latn", calendar: "gregory", ...(date ? { dateStyle: date } : {}), ...(time ? { timeStyle: time } : {}) });

const names = (locale) => {
  const months = new Intl.DateTimeFormat(locale, { timeZone: "UTC", month: "long", day: "numeric" });
  const weekdays = new Intl.DateTimeFormat(locale, { timeZone: "UTC", weekday: "long" });
  return {
    months: new Set([...Array(12).keys()].map((m) => months.formatToParts(utc(2026, m + 1, 5, 0, 0, 0)).find((p) => p.type === "month").value)),
    weekdays: new Set([...Array(7).keys()].map((d) => weekdays.format(utc(2026, 3, 1 + d, 0, 0, 0)))),
  };
};

// Whether a field pads to two digits shows in the start's values, all
// below ten, as in the end's hour of 10: a type with a value of a leading
// zero anywhere in the range pads everywhere.
const padded = (parts) => new Set(parts.filter((p) => /^0\d/.test(p.value)).map((p) => p.type));

// The pattern of a range's parts, and where its end's parts begin: the
// length of the pattern when the range shows one time.
const pattern = (parts, known) => {
  const hours12 = parts.some((p) => p.type === "dayPeriod");
  const pads = padded(parts);
  const digits = (value, letter) => pads.has(value) ? letter + letter : letter;
  let out = "", split = -1;
  for (const part of parts) {
    if (part.source === "endRange" && split < 0) split = Buffer.byteLength(out);
    let token;
    switch (part.type) {
      case "literal": token = quote(part.value); break;
      case "year": token = part.value.length === 2 ? "yy" : "y"; break;
      case "month": token = /^\d+$/.test(part.value) ? digits(part.type, "M") : known.months.has(part.value) ? "MMMM" : "MMM"; break;
      case "day": token = digits(part.type, "d"); break;
      case "weekday": token = known.weekdays.has(part.value) ? "EEEE" : "E"; break;
      case "dayPeriod": token = "a"; break;
      case "hour": token = digits(part.type, hours12 ? "h" : "H"); break;
      case "minute": token = digits(part.type, "m"); break;
      case "second": token = digits(part.type, "s"); break;
      default: return null; // a field the formatter has no letter of
    }
    out += token;
  }
  return { pattern: out, split: split < 0 ? Buffer.byteLength(out) : split };
};

let z = "//! Generated by scripts/i18n-intervals-cldr.mjs from the engine's CLDR data; do not edit.\n";
z += "//! Per locale, the patterns of ranges by date style (none, short, medium,\n";
z += "//! long, full), time style (none, short, medium) and the field two times\n";
z += "//! first differ in (year, month, day, day period, hour, minute, second):\n";
z += "//! the start's part of `pattern` before `split`, the end's after it.\n\n";
z += "pub const Interval = struct { pattern: []const u8, split: u16 };\n";
z += "pub const Locale = struct { tag: []const u8, patterns: [5][3][7]?Interval };\n\n";
z += "pub const locales = [_]Locale{\n";
for (const l of locales) {
  const known = names(l);
  z += `    .{ .tag = ${zig(l)}, .patterns = .{\n`;
  for (const date of dateStyles) {
    z += "        .{\n";
    for (const time of timeStyles) {
      if (!date && !time) {
        z += "            .{ null, null, null, null, null, null, null },\n";
        continue;
      }
      const f = new Intl.DateTimeFormat(l, options(date, time));
      const list = fields.map((field) => {
        const p = pattern(f.formatRangeToParts(start, ends[field]), known);
        return p === null ? "null" : `.{ .pattern = ${zig(p.pattern)}, .split = ${p.split} }`;
      });
      z += `            .{ ${list.join(", ")} },\n`;
    }
    z += "        },\n";
  }
  z += "    } },\n";
}
z += "};\n";
writeFileSync(new URL("../src/i18n/cldr_intervals.zig", import.meta.url), z);

// Outputs to compare with, as [locale, date style, time style, start,
// end, offset in minutes, the start alone, the range] rows.
const rows = [];
const cases = [
  [utc(2026, 1, 5, 10, 0, 0), utc(2026, 1, 9, 11, 30, 0)],
  [utc(2026, 1, 5, 10, 0, 0), utc(2026, 2, 9, 11, 30, 0)],
  [utc(2025, 12, 30, 10, 0, 0), utc(2026, 1, 2, 11, 30, 0)],
  [utc(2026, 1, 5, 10, 0, 0), utc(2026, 1, 5, 11, 30, 0)],
  [utc(2026, 1, 5, 10, 0, 0), utc(2026, 1, 5, 14, 15, 0)],
  [utc(2026, 1, 5, 10, 0, 0), utc(2026, 1, 5, 10, 45, 0)],
  [utc(2026, 1, 5, 10, 0, 5), utc(2026, 1, 5, 10, 0, 40)],
  [utc(2026, 1, 5, 10, 0, 0), utc(2026, 1, 5, 10, 0, 0)],
  [utc(2026, 7, 20, 23, 50, 0), utc(2026, 7, 21, 0, 10, 0)],
];
for (const l of locales) for (const date of dateStyles) for (const time of timeStyles) {
  if (!date && !time) continue;
  // An offset other than UTC's, for one combination of styles.
  for (const offset of date === "medium" && time === "short" ? [0, 330] : [0]) {
    const f = new Intl.DateTimeFormat(l, { ...options(date, time), timeZone: offset ? "+05:30" : "UTC" });
    for (const [a, b] of cases) rows.push([l, date ?? "", time ?? "", a.getTime() / 1000, b.getTime() / 1000, offset, f.format(a), f.formatRange(a, b)]);
  }
}
mkdirSync(new URL("../src/i18n/testdata/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/i18n/testdata/intervals.json", import.meta.url), "[" + rows.map((r) => JSON.stringify(r)).join(",\n") + "]\n");
console.log(rows.length + " cases");
