param([string]$SdkVersion = '10.0.26100.0')
$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path -Parent $PSScriptRoot
$sdkRoot = Join-Path ${env:ProgramFiles(x86)} 'Windows Kits/10'
$compiler = Join-Path $sdkRoot "bin/$SdkVersion/x64/fxc.exe"
if (!(Test-Path -LiteralPath $compiler)) { throw "Windows SDK $SdkVersion is required only to regenerate the shader." }
$source = Join-Path $taskRoot 'src/ui/shaders/gaussian.hlsl'
$output = Join-Path $taskRoot '.validation/drawing/gaussian-shader-offline'
New-Item -ItemType Directory -Path $output -Force | Out-Null
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('/* Generated by scripts/generate-gaussian-shader.ps1. Normal builds use these offline bytes. */')
$stages = [System.Collections.Generic.List[object]]::new()
foreach ($stage in @('vertex', 'pixel')) {
    $target = if ($stage -eq 'vertex') { 'vs_4_0' } else { 'ps_4_0' }
    $binary = Join-Path $output "gaussian-$stage.dxbc"
    & $compiler /nologo /Ges /Gis /O3 /T $target /E $stage /Fo $binary $source
    if ($LASTEXITCODE -ne 0) { throw "Gaussian $stage shader compilation failed." }
    $bytes = [System.IO.File]::ReadAllBytes($binary)
    $lines.Add("static const unsigned char zg_gaussian_$stage[] = {")
    for ($index = 0; $index -lt $bytes.Length; $index += 16) {
        $end = [Math]::Min($index + 16, $bytes.Length)
        $values = for ($offset = $index; $offset -lt $end; $offset++) { '0x{0:x2}' -f $bytes[$offset] }
        $lines.Add('    ' + ($values -join ',') + ',')
    }
    $lines.Add('};')
    $stages.Add([ordered]@{ stage = $stage; profile = $target; bytecode_bytes = $bytes.Length; bytecode_sha256 = (Get-FileHash -LiteralPath $binary).Hash.ToLowerInvariant() })
}
[System.IO.File]::WriteAllText((Join-Path $taskRoot 'src/ui/shaders/gaussian_shader.h'), ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
$metadata = [ordered]@{ schema = 1; sdk = $SdkVersion; compiler_version = (Get-Item -LiteralPath $compiler).VersionInfo.FileVersion; compiler_sha256 = (Get-FileHash -LiteralPath $compiler).Hash.ToLowerInvariant(); source_sha256 = (Get-FileHash -LiteralPath $source).Hash.ToLowerInvariant(); flags = @('/Ges','/Gis','/O3'); stages = $stages }
$metadata | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $taskRoot 'src/ui/shaders/gaussian_shader.json') -Encoding utf8NoBOM
$stages | ConvertTo-Json
