// Generates src/i18n/cldr_relative.zig, the relative time words and
// patterns of the locales src/i18n/number.zig lists, from the CLDR data of
// the JavaScript engine's Intl.RelativeTimeFormat (ICU), and
// src/i18n/testdata/relative.json, the outputs the tests compare with.
//
//     bun scripts/i18n-relative-cldr.mjs   (or node)
import { writeFileSync, mkdirSync } from "node:fs";

const locales = ["en", "en-IN", "hi", "de", "de-CH", "fr", "es", "es-MX", "it", "pt", "pt-PT", "nl", "ru", "uk", "pl", "cs", "sv", "nb", "fi", "da", "tr", "ja", "zh", "ko", "he", "ar", "fa"];
const units = ["second", "minute", "hour", "day", "week", "month", "quarter", "year"];
const styles = ["long", "short", "narrow"];
const categories = ["zero", "one", "two", "few", "many", "other"];
const NUMBER = "\x01";
const numberParts = new Set(["integer", "group", "decimal", "fraction"]);

const zig = (s) => '"' + Array.from(s).map((c) => {
  const p = c.codePointAt(0);
  if (c === '"' || c === "\\") return "\\" + c;
  if (p < 0x20 || p === 0x7f) return "\\x" + p.toString(16).padStart(2, "0");
  if (p >= 0x80 && (p < 0xa1 || (p >= 0x200b && p <= 0x200f) || (p >= 0x202a && p <= 0x202f) || p === 0x061c || p === 0x2066 || p === 0x2069)) return "\\u{" + p.toString(16) + "}";
  return c;
}).join("") + '"';

const template = (parts) => {
  let out = "", inNumber = false;
  for (const part of parts) {
    if (numberParts.has(part.type)) {
      if (!inNumber) out += NUMBER;
      inNumber = true;
      continue;
    }
    inNumber = false;
    out += part.value;
  }
  return out;
};

// A number of each plural category the locale has, as Intl.PluralRules
// selects it.
const candidates = [...Array(201).keys(), 1000, 10000, 100000, 1000000, 0.5, 1.5, 2.5, 0.1, 1.1, 2.1, 0.25];
const samples = (locale) => {
  const rules = new Intl.PluralRules(locale);
  const out = {};
  for (const n of candidates) {
    const c = rules.select(n);
    if (!(c in out)) out[c] = n;
  }
  return out;
};

let z = "//! Generated by scripts/i18n-relative-cldr.mjs from the engine's CLDR data; do not edit.\n";
z += "//! Per locale, style and unit: the words for -2 to 2 (null where the\n";
z += "//! locale has none) and the past and future patterns of each plural\n";
z += "//! category, with \\x01 where the number goes.\n\n";
z += "pub const Unit = struct { words: [5]?[]const u8, past: [6]?[]const u8, future: [6]?[]const u8 };\n";
z += "pub const Locale = struct { tag: []const u8, styles: [3][8]Unit };\n\n";
z += "pub const locales = [_]Locale{\n";
for (const l of locales) {
  const sample = samples(l);
  z += `    .{ .tag = ${zig(l)}, .styles = .{\n`;
  for (const style of styles) {
    const always = new Intl.RelativeTimeFormat(l, { style, numeric: "always", numberingSystem: "latn" });
    const auto = new Intl.RelativeTimeFormat(l, { style, numeric: "auto", numberingSystem: "latn" });
    z += "        .{\n";
    for (const unit of units) {
      const words = [-2, -1, 0, 1, 2].map((v) => {
        // A word is what numeric "auto" writes instead of the pattern; a
        // pattern of one without a digit ("לפני שנייה") is not one.
        const word = auto.format(v, unit);
        return word === always.format(v, unit) ? null : word;
      });
      const patterns = (sign) => categories.map((c) => c in sample ? template(always.formatToParts(sign * sample[c], unit)) : null);
      const list = (xs) => ".{ " + xs.map((x) => x === null ? "null" : zig(x)).join(", ") + " }";
      z += `            .{ .words = ${list(words)}, .past = ${list(patterns(-1))}, .future = ${list(patterns(1))} },\n`;
    }
    z += "        },\n";
  }
  z += "    } },\n";
}
z += "};\n";
writeFileSync(new URL("../src/i18n/cldr_relative.zig", import.meta.url), z);

// Outputs to compare with, as [locale, style, numeric, unit, value,
// negative zero, output] rows ("decimal" rows calibrate plain numbers).
const rows = [];
const always = [-0, 1, -1, 2, 5, -21, 1.5, 1234.5];
const auto = [-2, -1, 0, 1, 2, 1.001, -1.004, 3];
for (const l of locales) {
  rows.push([l, "decimal", "", "", 1234.5, false, new Intl.NumberFormat(l, { numberingSystem: "latn" }).format(1234.5)]);
  for (const style of styles) for (const [numeric, values] of [["always", always], ["auto", auto]]) {
    const f = new Intl.RelativeTimeFormat(l, { style, numeric, numberingSystem: "latn" });
    // JSON has no negative zero.
    for (const unit of units) for (const v of values) rows.push([l, style, numeric, unit, v, Object.is(v, -0), f.format(v, unit)]);
  }
}
mkdirSync(new URL("../src/i18n/testdata/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/i18n/testdata/relative.json", import.meta.url), "[" + rows.map((r) => JSON.stringify(r)).join(",\n") + "]\n");
console.log(rows.length + " cases");
