param([string]$SdkVersion = '10.0.26100.0')
$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path -Parent $PSScriptRoot
$sdkRoot = Join-Path ${env:ProgramFiles(x86)} 'Windows Kits/10'
$compiler = Join-Path $sdkRoot "bin/$SdkVersion/x64/fxc.exe"
$includes = Join-Path $sdkRoot "Include/$SdkVersion/um"
if (!(Test-Path -LiteralPath $compiler)) { throw "Windows SDK $SdkVersion is required only to regenerate the shader." }
$source = Join-Path $taskRoot 'src/ui/shaders/gradient_interpolation.hlsl'
$output = Join-Path $taskRoot '.zig-cache/managed/gradient-interpolation-shader'
New-Item -ItemType Directory -Path $output -Force | Out-Null
$binary = Join-Path $output 'gradient_interpolation.dxbc'
& $compiler /nologo /Ges /Gis /O3 /T ps_4_0 /E main /I $includes /Fo $binary $source
if ($LASTEXITCODE -ne 0) { throw 'Shader compilation failed.' }
$bytes = [System.IO.File]::ReadAllBytes($binary)
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('/* Generated by scripts/generate-gradient-interpolation-shader.ps1. Normal builds use these offline bytes. */')
$lines.Add('static const unsigned char zg_gradient_interpolation_shader[] = {')
for ($index = 0; $index -lt $bytes.Length; $index += 16) {
    $end = [Math]::Min($index + 16, $bytes.Length)
    $values = for ($offset = $index; $offset -lt $end; $offset++) { '0x{0:x2}' -f $bytes[$offset] }
    $lines.Add('    ' + ($values -join ',') + ',')
}
$lines.Add('};')
$header = Join-Path $taskRoot 'src/ui/shaders/gradient_interpolation_shader.h'
[System.IO.File]::WriteAllText($header, ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
$metadata = [ordered]@{ schema = 1; sdk = $SdkVersion; compiler_version = (Get-Item -LiteralPath $compiler).VersionInfo.FileVersion; compiler_sha256 = (Get-FileHash -LiteralPath $compiler -Algorithm SHA256).Hash.ToLowerInvariant(); source_sha256 = (Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash.ToLowerInvariant(); included_source_sha256 = (Get-FileHash -LiteralPath (Join-Path $taskRoot 'src/ui/shaders/gradient.hlsl') -Algorithm SHA256).Hash.ToLowerInvariant(); bytecode_sha256 = (Get-FileHash -LiteralPath $binary -Algorithm SHA256).Hash.ToLowerInvariant(); bytecode_bytes = $bytes.Length; flags = @('/Ges','/Gis','/O3','/T','ps_4_0','/E','main') }
$metadata | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $taskRoot 'src/ui/shaders/gradient_interpolation_shader.json') -Encoding utf8NoBOM
Write-Output "Prepared $($bytes.Length) bytes of offline gradient shader."
