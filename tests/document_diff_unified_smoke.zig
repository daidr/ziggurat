const modified = "header\nreplacement 文\nsame\nlast";
fn expectText(document: *d.Document, expected: []const u8) !void {
    var bytes: [1024]u8 = undefined;
    try std.testing.expectEqualStrings(expected, bytes[0..try document.read(.{ .start = 0, .end = try document.byteLength() }, &bytes)]);
}
fn invalidFilter(state: *Harness, frame: *ui.Frame) !void {
    try std.testing.expectError(error.InvalidParagraphs, state.adapters[0].drawParagraphs(frame, state.viewport, &.{ 1, 1 }, ui.Color.rgb(0)));
}
fn largeGhosts(allocator: std.mem.Allocator, state: *Harness) !void {
    var source: std.ArrayList(u8) = .empty;
    defer source.deinit(allocator);
    for (0..200) |_| try source.appendSlice(allocator, "removed line\n");
    const a = state.inbox.pair.a;
    const b = state.inbox.pair.b;
    _ = try state.adapters[0].replaceMany(try a.version(), &.{.{ .range = .{ .start = 0, .end = try a.byteLength() }, .text = source.items }});
    _ = try state.adapters[1].replaceMany(try b.version(), &.{.{ .range = .{ .start = 0, .end = try b.byteLength() }, .text = "" }});
    const before = try state.adapters[0].stats();
    try state.refresh();
    try std.testing.expectEqual(@as(usize, 200), (try state.view.info()).total_rows);
    const shaped = try state.adapters[0].stats();
    try std.testing.expect(shaped.shaped_bytes - before.shaped_bytes < source.items.len / 2);
    const revision_a = try a.version();
    try state.paint();
    try state.click(bounds.x + 10, bounds.y + 3);
    try std.testing.expectEqual(@as(usize, 0), (try b.selection()).caret);
    try state.insert();
    try expectText(b, "x");
    try std.testing.expectEqual(revision_a, try a.version());
    try std.testing.expect((try state.view.info()).comparison_required);
    _ = try state.adapters[1].undo();
    try expectText(b, "");
    try state.refresh();
    try state.view.focus();
    _ = try state.view.handleEvent(.{ .key_input = .{ .key = .end, .modifiers = .{ .control = true } } }, bounds, state.parameters);
    try std.testing.expect((try state.view.info()).anchor_row > 180);
    try state.paint();
    _ = try state.view.scrollBy(-1000000);
    try state.view.prepare(bounds, state.parameters);
    state.after_draw = invalidFilter;
    state.expected = error.InvalidParagraphs;
    const frames = state.context.frames;
    try state.paint();
    try std.testing.expectEqual(frames, state.context.frames);
    state.after_draw = null;
    state.expected = null;
    try state.view.prepare(bounds, state.parameters);
    const a_stats = try state.adapters[0].stats();
    const b_stats = try state.adapters[1].stats();
    try state.paint();
    try std.testing.expectEqual(a_stats.shaped_batches, (try state.adapters[0].stats()).shaped_batches);
    try std.testing.expectEqual(b_stats.shaped_batches, (try state.adapters[1].stats()).shaped_batches);
    const first = "top\nremoved0\nsame\nremoved1\nlast";
    const second = "top\nnew0\nsame\nnew1\nlast";
    for (state.adapters, [_]*d.Document{ a, b }, [_][]const u8{ first, second }) |adapter, document, text| _ = try adapter.replaceMany(try document.version(), &.{.{ .range = .{ .start = 0, .end = try document.byteLength() }, .text = text }});
    try state.refresh();
    try state.paint();
    var rows: [96]viewing.editable.Row = undefined;
    var second_ghost: ?f32 = null;
    for (try state.view.rowInfo(&rows)) |row| if (row.hunk == 1 and row.b == null) {
        second_ghost = bounds.y + row.y + 2;
    };
    try std.testing.expect(second_ghost != null);
    try state.click(bounds.x + 10, second_ghost.?);
    try std.testing.expectEqual(@as(usize, 1), (try state.view.info()).selected_hunk.?);
    _ = try state.view.revert(1);
    try state.view.prepare(bounds, state.parameters);
    try expectText(b, "top\nnew0\nsame\nremoved1\nlast");
    _ = try state.adapters[1].undo();
    try expectText(b, second);
    try state.refresh();
}
pub fn run(allocator: std.mem.Allocator) !void {
    const a = try d.Document.create(allocator, std.Thread.getCurrentId(), original, .{});
    defer a.close() catch unreachable;
    const b = try d.Document.create(allocator, std.Thread.getCurrentId(), modified, .{});
    defer b.close() catch unreachable;
    const engine = try t.Engine.create(allocator, std.Thread.getCurrentId(), .{});
    defer engine.close() catch unreachable;
    const adapters: [2]*editing.Adapter = .{ try editing.Adapter.create(allocator, a, engine, .{}), try editing.Adapter.create(allocator, b, engine, .{}) };
    defer for (adapters) |adapter| adapter.close() catch unreachable;
    const inbox = try viewing.Inbox.create(allocator, .{ .a = a, .b = b }, .{});
    defer inbox.close() catch unreachable;
    var state: Harness = .{ .inbox = inbox, .adapters = adapters };
    const app = try z.App.initWithOptions(allocator, .{ .diagnostics_sink = .{ .context = &state, .emit = Harness.diagnostic } });
    defer app.deinit();
    state.window = try app.createWindow(.{ .width = 430, .height = 270 });
    defer _ = state.window.destroy() catch unreachable;
    state.parameters.scale = if (builtin.os.tag == .windows) @as(f32, @floatFromInt(c.GetDpiForWindow(state.window.nativeHandle()))) / 96 else @floatFromInt(gtk_widget_get_scale_factor(state.window.nativeHandle().?));
    var failing = std.testing.FailingAllocator.init(allocator, .{});
    state.view = try viewing.EditableUnified.create(failing.allocator(), inbox, adapters[0], adapters[1], state.window, .{});
    defer state.view.close() catch unreachable;
    try state.refresh();
    state.context = ui.Context.init(&state, Harness.draw, Harness.action);
    state.context.render_mode = .gdi;
    state.context.on_input = Harness.input;
    try state.context.attach(state.window);
    try state.paint();
    try std.testing.expectEqual(viewing.editable.Mode.unified, (try state.view.info()).mode);
    var rows: [96]viewing.editable.Row = undefined;
    var ghost_y: ?f32 = null;
    var added_y: ?f32 = null;
    var ghost_glyphs: usize = 0;
    for (try state.view.rowInfo(&rows)) |row| if (row.hunk != null) {
        const y = bounds.y + row.y;
        const ghost = row.b == null;
        if (ghost) {
            if (ghost_y == null) ghost_y = y;
            const end_y: usize = @intFromFloat(@min(y + row.height, bounds.y + bounds.height));
            const begin_y: usize = @intFromFloat(@max(y, bounds.y));
            for (begin_y..@max(begin_y, end_y)) |yy| for (10..200) |xx| {
                const color = try state.pixel(@floatFromInt(xx), @floatFromInt(yy));
                if ((color & 255) < 128 and ((color >> 8) & 255) < 128 and ((color >> 16) & 255) < 128) ghost_glyphs += 1;
            };
        } else if (added_y == null) added_y = y;
        try std.testing.expectEqual(if (ghost) @as(u32, 0xffe9e9) else 0xe5f6e9, try state.pixel(bounds.x + bounds.width - 2, y + 1));
    };
    try std.testing.expect(ghost_y != null and added_y != null and ghost_y.? < added_y.? and ghost_glyphs > 10);
    state.viewport.width = 220;
    try state.view.prepare(state.viewport, state.parameters);
    try state.paint();
    const native_added = try b.line(1);
    var checked_alignment = false;
    for (try state.view.rowInfo(&rows)) |row| if (row.b == 1) {
        const rect = (try adapters[1].positionRect(try b.version(), native_added.start, .downstream)).?;
        try std.testing.expectApproxEqAbs(bounds.y + row.y, rect.y, 0.001);
        checked_alignment = true;
    };
    try std.testing.expect(checked_alignment);
    state.viewport = bounds;
    try state.view.prepare(bounds, state.parameters);
    // Ghosts never manufacture a modified-source offset or another selection.
    const selected_b = try b.selection();
    const revision_a = try a.version();
    const revision_b = try b.version();
    try state.click(bounds.x + 50, ghost_y.? + 3);
    try std.testing.expectEqual(selected_b, try b.selection());
    try std.testing.expectEqual(revision_b, try b.version());
    try std.testing.expectEqual(revision_a, try a.version());
    try std.testing.expect(!try adapters[0].isBound() and try adapters[1].isBound());
    try std.testing.expect((try state.view.info()).selected_hunk != null);
    // Added text has the same visible geometry and byte identity as Adapter B.
    try state.click(bounds.x + 2, added_y.? + 3);
    const added = try b.line(1);
    try std.testing.expect((try b.selection()).caret >= added.start and (try b.selection()).caret <= added.end);
    try state.key(0x24, 0xff50); // Native Home.
    try state.key(0x26, 0xff52); // Up skips read-only ghost rows.
    try std.testing.expect((try b.selection()).caret < added.start);
    try state.key(0x28, 0xff54);
    try std.testing.expect((try b.selection()).caret >= added.start);
    const before = try b.byteLength();
    try state.insert();
    try std.testing.expectEqual(before + 1, try b.byteLength());
    try std.testing.expect((try state.view.info()).comparison_required);
    try expectText(a, original);
    _ = try adapters[1].undo();
    try expectText(b, modified);
    try state.refresh();
    try state.paint();
    _ = try state.view.handleEvent(.{ .text_preedit = .{ .text = "候\n选", .selection_start = 0, .selection_end = 3 } }, bounds, state.parameters);
    try std.testing.expect((try state.view.info()).composition_identity);
    try state.paint();
    _ = try state.view.handleEvent(.text_preedit_cancel, bounds, state.parameters);
    try std.testing.expect(!(try state.view.info()).comparison_required);
    try state.paint();
    _ = try state.view.revert(0);
    try state.view.prepare(bounds, state.parameters);
    try expectText(b, original);
    try std.testing.expect((try state.view.info()).comparison_required);
    _ = try adapters[1].undo();
    try expectText(b, modified);
    try state.refresh();
    // Sorted filter validation poisons a failed Frame; no lease can escape.
    const versions = .{ try adapters[0].viewVersion(), try adapters[1].viewVersion() };
    failing.fail_index = failing.alloc_index;
    var narrower = bounds;
    narrower.width -= 20;
    try std.testing.expectError(error.OutOfMemory, state.view.prepare(narrower, state.parameters));
    failing.fail_index = std.math.maxInt(usize);
    try std.testing.expectEqual(versions[0], try adapters[0].viewVersion());
    try std.testing.expectEqual(versions[1], try adapters[1].viewVersion());
    try state.view.prepare(bounds, state.parameters);
    try largeGhosts(allocator, &state);
    state.fail_frame = true;
    state.expected = error.InvalidGeometry;
    try state.paint();
    state.fail_frame = false;
    state.expected = null;
    try state.view.prepare(bounds, state.parameters);
    state.close_frame = true;
    try state.paint();
    try app.dispatch();
    try std.testing.expectEqual(@as(usize, 0), app.resourceStats().allocated_records);
    std.debug.print("unified diff native passed: removed/added order and pixels, read-only ghost input, sole modified client/edit/undo, IME identity/cancel, atomic revert/OOM, failed Frame/close resources=0\n", .{});
}
